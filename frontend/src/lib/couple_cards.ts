// 150 questions for couples, organised into 6 decks of 25, in all five UI
// languages. Pure static data, no backend, no auth. Rendered by
// CoupleCardsPage.tsx as a one-card-at-a-time conversation tool on
// /eszkozok/100-kerdes-eskuvo-elott (HU) and
// /tools/100-questions-before-marriage (EN).
//
// The four numbered Level decks are the "100 questions" the page is named
// after; First Date and Lemonade are the two hidden accent packs either
// side of them.
//
// Each deck is independent: deck order is fixed in this array, but card
// order within a deck is randomised on first open and cached in
// localStorage so a returning visitor doesn't get the same shuffle twice
// in a session.
//
// Card COPY is data, not UI chrome, so it does not live in locales/*.ts and
// does not go through t(). Every deck carries a full array per UI locale
// (hr and de ship partial UI trees, but the cards themselves are complete),
// and `deckQuestions` is the only reader.

import { type UiLocale, UI_LOCALES } from "@shared/locales";

export type DeckId = "firstdate" | "roots" | "everyday" | "closeness" | "deepwater" | "lemonade";

/** One array of card text per UI locale. A deck that has not shipped yet
 *  carries five empty arrays, which is what `deckHasCards` reads. */
export type DeckQuestions = Readonly<Record<UiLocale, readonly string[]>>;

export interface Deck {
  id: DeckId;
  /** Locale-keyed UI labels live in tools.couple_cards.*: these are the
   *  card-content strings the deck name short label maps to via t().
   *  We keep the actual titles in locales/{hu,en,es,hr,de}.ts so the deck
   *  picker reads the same translation memory as the rest of the page. */
  titleKey: string;
  blurbKey: string;
  questions: DeckQuestions;
}

