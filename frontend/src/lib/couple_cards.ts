export const DECK_SIZE = 25;

/** The card list to show a visitor. Falls back to EN when a locale's array
 *  is missing or empty, the same per-key degradation `t()` applies to UI
 *  copy: a half-translated deck reads as English rather than as blanks. */
export function deckQuestions(deck: Deck, locale: UiLocale): readonly string[] {
  const list = deck.questions[locale];
  if (list && list.length > 0) return list;
  return deck.questions.en;
}

/** A deck is playable once its cards have landed. Asked of EN because EN is
 *  what every other locale falls back to. */
export function deckHasCards(deck: Deck): boolean {
  return deck.questions.en.length > 0;
}

/** Every locale a deck carries cards in, in switcher order. Exported for
 *  the admin feedback triage, which has to look a vote's snapshot up by the
 *  locale the visitor was reading in. */
